// src/index.js
import 'dotenv/config';
import Fastify from 'fastify';
import cors from '@fastify/cors';
import jwt from '@fastify/jwt';

import { authRoutes } from './routes/auth.js';
import { homeRoutes } from './routes/home.js';
import { medicinesRoutes } from './routes/medicines.js';
import { familyRoutes } from './routes/family.js';
import { settingsRoutes } from './routes/settings.js';
import { aiRoutes } from './routes/ai.js';
import { drugSearchRoutes } from './routes/drug_search.js';

const fastify = Fastify({
  logger: true,
  bodyLimit: 52428800,
});

// ?? CORS ??????????????????????????????????????????
await fastify.register(cors, {
  origin: true,
  methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'],
  allowedHeaders: ['Content-Type', 'Authorization'],
});

// ?? JWT ???????????????????????????????????????????
await fastify.register(jwt, {
  secret: process.env.JWT_SECRET ?? 'dev-secret-change-in-production',
});

// authenticate ?곗퐫?덉씠?????쇱슦??onRequest ?먯꽌 ?ъ슜
fastify.decorate('authenticate', async (req, reply) => {
  try {
    await req.jwtVerify();
  } catch {
    reply.status(401).send({ error: '?몄쬆???꾩슂?⑸땲?? ?ㅼ떆 濡쒓렇?명빐二쇱꽭??' });
  }
});

// ?? ?ъ뒪泥댄겕 ??????????????????????????????????????
fastify.get('/health', async () => ({ status: 'ok', timestamp: new Date().toISOString() }));

// ?? ?쇱슦???깅줉 ???????????????????????????????????
await fastify.register(authRoutes);
await fastify.register(homeRoutes);
await fastify.register(medicinesRoutes);
await fastify.register(familyRoutes);
await fastify.register(settingsRoutes);
await fastify.register(aiRoutes);
await fastify.register(drugSearchRoutes);

// ?? ?쒕쾭 ?쒖옉 ?????????????????????????????????????
const port = Number(process.env.PORT ?? 3000);
const host = process.env.HOST ?? '0.0.0.0';

try {
  await fastify.listen({ port, host });
  console.log(`Link26 API ?쒕쾭 ?ㅽ뻾 以? http://${host}:${port}`);
} catch (err) {
  fastify.log.error(err);
  process.exit(1);
}





